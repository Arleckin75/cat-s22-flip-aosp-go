#!/usr/bin/env python3
"""Generate device/cat/s22/cover/cover_font.h: anti-aliased bitmap fonts for the
128x128 cover display, rendered from Roboto (Apache License 2.0).

Usage: gen_cover_font.py <android-source-root> <output.h>
Requires Pillow. The header is committed; rerun only to change sizes/charset.
"""
from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont

TEXT_CHARS = (
    [chr(c) for c in range(0x20, 0x7F)]
    + ['Ё', 'ё'] + [chr(c) for c in range(0x0410, 0x0450)]
    + ['«', '»', '°', '·', '—', '…', '№']
)
CLOCK_CHARS = list('0123456789:')


def load(root, weight, size):
    variable = root / 'external/roboto-fonts/Roboto-Regular.ttf'
    font = ImageFont.truetype(str(variable), size)
    try:
        font.set_variation_by_axes([weight])
    except (OSError, AttributeError):
        font = ImageFont.truetype(str(root / 'external/roboto-fonts/RobotoStatic-Regular.ttf'), size)
    return font


def render(name, font, chars, out):
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in chars:
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(data)
        if w and h:
            image = Image.new('L', (w, h), 0)
            ImageDraw.Draw(image).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            data += image.tobytes()
        glyphs.append((ord(ch), w, h, x0, -y0, round(font.getlength(ch)), offset))
    out.append(f'static const uint8_t {name}_alpha[] = {{')
    for i in range(0, len(data), 24):
        out.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const cover_glyph_t {name}_glyphs[] = {{')
    for g in sorted(glyphs):
        out.append('    {0x%04X, %d, %d, %d, %d, %d, %d},' % g)
    out.append('};')
    out.append(f'static const cover_font_t {name} = {{{name}_glyphs, {len(glyphs)}, '
               f'{name}_alpha, {ascent}, {ascent + descent}}};')
    out.append('')


def main(root, output):
    root = Path(root)
    out = [
        '// Generated by tools/gen_cover_font.py from Roboto (external/roboto-fonts).',
        '// Roboto is licensed under the Apache License, Version 2.0.',
        '#pragma once',
        '#include <stdint.h>',
        '',
        'typedef struct {',
        '    uint32_t cp;      /* Unicode code point */',
        '    uint8_t w, h;     /* bitmap size */',
        '    int8_t left;      /* x offset from pen position */',
        '    int8_t top;       /* bitmap top, pixels above the baseline */',
        '    uint8_t advance;  /* pen advance */',
        '    uint32_t offset;  /* into the 8-bit alpha array */',
        '} cover_glyph_t;',
        '',
        'typedef struct {',
        '    const cover_glyph_t *glyphs;  /* sorted by code point */',
        '    int count;',
        '    const uint8_t *alpha;',
        '    int ascent, height;',
        '} cover_font_t;',
        '',
    ]
    render('font_small', load(root, 400, 13), TEXT_CHARS, out)
    render('font_medium', load(root, 500, 16), TEXT_CHARS, out)
    render('font_clock', load(root, 300, 44), CLOCK_CHARS, out)
    Path(output).write_text('\n'.join(out))
    print('Wrote', output)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
